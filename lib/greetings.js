// 시간대 문구를 우선하되, 가끔 서비스 성격 문구를 섞는다
const GENERAL_RATIO = 0.3

export function getGreetingKey(hour) {
  const bucket = GREETING_BUCKETS.find(b => hour >= b.start && hour < b.end)
  return bucket ? bucket.key : 'morning'
}

const sample = list => list[Math.floor(Math.random() * list.length)]

export function pickGreeting(date = new Date()) {
  if (Math.random() < GENERAL_RATIO) {
    return sample(GENERAL_GREETINGS)
  }
  return sample(GREETINGS[getGreetingKey(date.getHours())])
}
